def cc(body):
    return cc_window(body, path=TOOL)


def dl(href, label):
    return f'<a class="dl g" href="{href}" download>📥 {E(label)}</a> '


def design(cid, text):
    return code_block("설계서 예시 (내 것과 달라도 됩니다)", text=text, cid=cid, wrap=True)


def answers(rows):
    """검증 정답(접힘). rows: [(확인할 값, 정답)]"""
    return ('<details class="qa"><summary>샘플 데이터 정답 보기 (먼저 엑셀에서 직접 구한 뒤 펼치세요)</summary>'
            + table(["확인할 값", "정답"], rows) + "</details>")


def track(key, title, sub, who, problem, data_html, design_html, first, first_ok, feats, check_rows, extra="", first_label="첫 화면"):
    f_html = "".join(f"<p><b>기능 {i}</b> · {E(t)}</p>" + prompt(p) + f'<div class="okline">{o}</div>' for i, (t, p, o) in enumerate(feats, 1))
    return (f'<details class="trk" id="trk-{key}"><summary>트랙 {E(title)}<small>{E(sub)}</small></summary><div class="trk-b">'
            + table(["대상", "해결하는 문제"], [[who, problem]])
            + "<h4>4-1 · 데이터</h4>" + data_html
            + "<h4>3-10 · 설계서 예시</h4>" + design_html
            + f"<h4>4-3 · {first_label} 요청문</h4>" + prompt(first) + f'<div class="okline">{first_ok}</div>'
            + "<h4>4-4 · 기능 요청문 (하나씩, 매번 저장)</h4>" + f_html
            + "<h4>4-5 · 검증할 값 3개</h4>" + answers(check_rows) + extra + "</div></details>")


